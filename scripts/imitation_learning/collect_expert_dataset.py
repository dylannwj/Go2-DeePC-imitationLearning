    backward_names = ["backward_010", "backward_020", "backward_030"]
    lateral_names = ["lateral_left_010", "lateral_left_015", "lateral_right_010", "lateral_right_015", "lateral_left_020", "lateral_right_020"]
    yaw_names = [
        "yaw_left_020", "yaw_left_030", "yaw_left_040", "yaw_left_050",
        "yaw_right_020", "yaw_right_030", "yaw_right_040", "yaw_right_050",
    ]
    mixed_names = ["mixed_left", "mixed_right", "mixed_fast_left", "mixed_fast_right"]
    arc_names = ["forward_left_arc", "forward_right_arc", "fast_left_arc", "fast_right_arc"]
    diagonal_names = ["forward_left_lateral", "forward_right_lateral", "fast_left_lateral", "fast_right_lateral"]
    pattern = episode_id % 10
    internal: list[str]
    if pattern == 0:
        internal = [str(rng.choice(forward_names)), str(rng.choice(forward_names)), "standing", str(rng.choice(yaw_names)), str(rng.choice(yaw_names)), "standing", str(rng.choice(lateral_names)), str(rng.choice(lateral_names)), str(rng.choice(mixed_names)), str(rng.choice(forward_names))]
    elif pattern == 1:
        internal = [str(rng.choice(forward_names)), str(rng.choice(arc_names)), str(rng.choice(arc_names)), str(rng.choice(forward_names)), str(rng.choice(yaw_names)), str(rng.choice(yaw_names)), "standing", str(rng.choice(forward_names)), str(rng.choice(diagonal_names)), str(rng.choice(mixed_names))]
    elif pattern == 2:
        internal = ["standing", str(rng.choice(backward_names)), "standing", str(rng.choice(lateral_names)), str(rng.choice(lateral_names)), str(rng.choice(yaw_names)), str(rng.choice(yaw_names)), str(rng.choice(mixed_names)), str(rng.choice(forward_names)), str(rng.choice(arc_names))]
    elif pattern == 3:
        internal = [str(rng.choice(forward_names)), str(rng.choice(yaw_names)), str(rng.choice(forward_names)), str(rng.choice(yaw_names)), str(rng.choice(diagonal_names)), str(rng.choice(diagonal_names)), str(rng.choice(arc_names)), str(rng.choice(arc_names)), "standing", str(rng.choice(mixed_names))]
    elif pattern == 4:
        internal = [str(rng.choice(lateral_names)), str(rng.choice(lateral_names)), str(rng.choice(forward_names)), str(rng.choice(arc_names)), str(rng.choice(arc_names)), str(rng.choice(backward_names)), "standing", str(rng.choice(yaw_names)), str(rng.choice(mixed_names)), str(rng.choice(forward_names))]
    elif pattern == 5:
        internal = [str(rng.choice(forward_names)), str(rng.choice(forward_names)), str(rng.choice(arc_names)), str(rng.choice(arc_names)), str(rng.choice(lateral_names)), str(rng.choice(lateral_names)), str(rng.choice(yaw_names)), str(rng.choice(yaw_names)), str(rng.choice(mixed_names)), "standing"]
    elif pattern == 6:
        internal = [str(rng.choice(backward_names)), str(rng.choice(backward_names)), "standing", str(rng.choice(forward_names)), str(rng.choice(diagonal_names)), str(rng.choice(arc_names)), str(rng.choice(yaw_names)), str(rng.choice(lateral_names)), str(rng.choice(mixed_names)), str(rng.choice(forward_names))]
    elif pattern == 7:
        internal = [str(rng.choice(yaw_names)), str(rng.choice(yaw_names)), str(rng.choice(forward_names)), str(rng.choice(arc_names)), "standing", str(rng.choice(lateral_names)), str(rng.choice(diagonal_names)), str(rng.choice(mixed_names)), str(rng.choice(backward_names)), str(rng.choice(forward_names))]
    elif pattern == 8:
        internal = [str(rng.choice(diagonal_names)), str(rng.choice(diagonal_names)), str(rng.choice(arc_names)), str(rng.choice(arc_names)), str(rng.choice(forward_names)), str(rng.choice(yaw_names)), str(rng.choice(yaw_names)), "standing", str(rng.choice(lateral_names)), str(rng.choice(mixed_names))]
