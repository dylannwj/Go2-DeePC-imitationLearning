def empty_accumulator() -> dict[str, list[Any]]:
    return {name: [] for name in RAW_WIDTHS}


def append_accumulator(acc: dict[str, list[Any]], values: dict[str, Any]) -> None:
    for name in RAW_WIDTHS:
        acc[name].append(np.asarray(values[name]).copy())


def finalize_accumulator(acc: dict[str, list[Any]]) -> dict[str, np.ndarray]:
    result: dict[str, np.ndarray] = {}
    for name, (width, dtype) in RAW_WIDTHS.items():
        if acc[name]:
            values = np.asarray(acc[name], dtype=dtype)
            if width == 1:
                values = values.reshape(-1)
        else:
            shape = (0,) if width == 1 else (0, width)
            values = np.empty(shape, dtype=dtype)
        result[name] = values
    return result


def safety_reason(
    measured: dict[str, np.ndarray],
    raw_action: np.ndarray,
    preclip_torque: np.ndarray,
    actual_joint_limit: np.ndarray,
    nan_inf: np.ndarray,
) -> np.ndarray:
    reasons = np.full(len(raw_action), "none", dtype=object)
    fall = (
        measured["body_height"] < 0.12
    ) | (np.max(np.abs(measured["root_rpy"][:, :2]), axis=1) > 1.0)
    base = measured["base_contact"]
    torque = np.any(np.abs(preclip_torque) > EFFORT_LIMIT[None, :] + 1.0e-6, axis=1)
    for index in range(len(raw_action)):
        if nan_inf[index] or not np.isfinite(raw_action[index]).all():
            reasons[index] = "invalid_nan_or_inf"
        elif bool(base[index]):
            reasons[index] = "base_contact"
        elif bool(measured["body_height"][index] < 0.12):
            reasons[index] = "root_height_below_threshold"
        elif bool(np.max(np.abs(measured["root_rpy"][index, :2])) > 1.0):
            reasons[index] = "roll_or_pitch_threshold"
        elif bool(actual_joint_limit[index]):
            reasons[index] = "joint_limit_violation"
        elif bool(torque[index]):
            reasons[index] = "torque_limit_violation"
    return reasons


def run_batch(
    scene: Any,
    teacher: Any,
    schedules: list[dict[str, Any]],
    settle_steps: int,
    make_teacher_observation: Any,
) -> list[dict[str, Any]]:
    batch_size = len(schedules)
    duration_steps = len(schedules[0]["commands"])
    scene.reset()
    last_action = np.zeros((batch_size, ACTION_DIM), dtype=np.float32)
    settle_bad = np.zeros(batch_size, dtype=bool)

    # Settle is executed but deliberately excluded from the training rows.
    for _ in range(settle_steps):
        observed = scene.observe(last_action)
        zero = np.zeros((batch_size, COMMAND_DIM), dtype=np.float32)
        teacher_obs = teacher_input_batch(observed["state"], zero)
        actions = infer_teacher_batch(teacher, teacher_obs)
        target = DEFAULT_JOINT_POS[None, :] + ACTION_SCALE[None, :] * actions
        applied = np.clip(target, scene.joint_lower_policy[None, :], scene.joint_upper_policy[None, :]).astype(np.float32)
        current = observed["joint_position"]
        velocity = observed["joint_velocity"]
        preclip = KP[None, :] * (applied - current) - KD[None, :] * velocity
        scene.step(applied)
        measured = scene.observe(actions)
        finite = (
            np.isfinite(actions).all(axis=1)
            & np.isfinite(target).all(axis=1)
            & np.isfinite(preclip).all(axis=1)
            & np.isfinite(measured["root_position"]).all(axis=1)
            & np.isfinite(measured["joint_position"]).all(axis=1)
        )
        settle_bad |= (
            ~finite
            | measured["base_contact"]
            | (measured["body_height"] < 0.12)
            | (np.max(np.abs(measured["root_rpy"][:, :2]), axis=1) > 1.0)
            | np.any(np.abs(preclip) > EFFORT_LIMIT[None, :] + 1.0e-6, axis=1)
        )
        last_action = actions

    accumulators = [empty_accumulator() for _ in schedules]
    active = ~settle_bad
    reasons = ["settle_failure" if flag else "" for flag in settle_bad]
    for step in range(duration_steps):
        if not np.any(active):
            break
        observed = scene.observe(last_action)
        commands = np.asarray([schedule["commands"][step] for schedule in schedules], dtype=np.float32)
        teacher_obs = teacher_input_batch(observed["state"], commands)
        # Use the validated adapter for an explicit call-site audit.  The
        # vectorized adapter below is mathematically identical and is checked
        # against one scalar adapter invocation each batch.
        scalar_adapter = np.asarray(make_teacher_observation(observed["state"][0], commands[0]), dtype=np.float32)
        if not np.array_equal(scalar_adapter, teacher_obs[0]):
            raise RuntimeError("teacher observation adapter mismatch")
        student_state = student_state_batch(observed, last_action)
        student_input = np.concatenate((student_state, commands), axis=1).astype(np.float32)
        actions = infer_teacher_batch(teacher, teacher_obs)
        target = DEFAULT_JOINT_POS[None, :] + ACTION_SCALE[None, :] * actions
        applied = np.clip(target, scene.joint_lower_policy[None, :], scene.joint_upper_policy[None, :]).astype(np.float32)
        target_clip = np.any(np.abs(applied - target) > 1.0e-7, axis=1)
        current = observed["joint_position"]
        velocity = observed["joint_velocity"]
        preclip = KP[None, :] * (applied - current) - KD[None, :] * velocity
        torque_violation = np.any(np.abs(preclip) > EFFORT_LIMIT[None, :] + 1.0e-6, axis=1)
        applied_torque = np.asarray(scene.step(applied), dtype=np.float32)
        measured = scene.observe(actions)
        actual_joint_limit = np.any(
            (measured["joint_position"] < scene.joint_lower_policy[None, :] - 1.0e-6)
            | (measured["joint_position"] > scene.joint_upper_policy[None, :] + 1.0e-6),
            axis=1,
        )
        nan_inf = (
            ~np.isfinite(actions).all(axis=1)
            | ~np.isfinite(target).all(axis=1)
            | ~np.isfinite(preclip).all(axis=1)
            | ~np.isfinite(applied_torque).all(axis=1)
            | ~np.isfinite(measured["root_position"]).all(axis=1)
            | ~np.isfinite(measured["root_rpy"]).all(axis=1)
            | ~np.isfinite(measured["joint_position"]).all(axis=1)
            | ~np.isfinite(measured["joint_velocity"]).all(axis=1)
        )
        step_reasons = safety_reason(measured, actions, preclip, actual_joint_limit, nan_inf)
        for index, schedule in enumerate(schedules):
            if not active[index]:
                continue
            values = {
                "student_state": student_state[index],
                "desired_command": commands[index],
                "student_input": student_input[index],
                "teacher_obs": teacher_obs[index],
                "expert_action": actions[index],
                "expert_action_student_order": actions[index][POLICY_TO_SCENE],
                "q_target": target[index],
                "q_target_student_order": target[index][POLICY_TO_SCENE],
                "previous_expert_action": last_action[index],
                "previous_expert_action_student_order": last_action[index][POLICY_TO_SCENE],
                "base_position": measured["root_position"][index],
                "base_rpy": measured["root_rpy"][index],
                "base_linear_velocity": measured["body_linear_velocity"][index],
                "base_angular_velocity": measured["body_angular_velocity"][index],
                "joint_position": measured["joint_position"][index][POLICY_TO_SCENE],
                "joint_velocity": measured["joint_velocity"][index][POLICY_TO_SCENE],
                "foot_contacts": measured["foot_contacts"][index],
                "q_target_applied": applied[index],
                "preclip_torque": preclip[index],
                "applied_torque": applied_torque[index],
                "episode_id": schedule["episode_id"],
                "step_index": step,
                "seed": schedule["seed"],
                "command_segment_id": schedule["segment_ids"][step],
                "transition_window": schedule["transition_window"][step],
                "timestamp": step * CONTROL_DT,
                "fall_flag": step_reasons[index] in FALL_REASONS,
                "base_contact": bool(measured["base_contact"][index]),
                "actual_joint_limit_violation": bool(actual_joint_limit[index]),
                "q_target_clipping": bool(target_clip[index]),
                "torque_limit_violation": bool(torque_violation[index]),
                "nan_inf_flag": bool(nan_inf[index]),
            }
            append_accumulator(accumulators[index], values)
            if step_reasons[index] != "none":
                active[index] = False
                reasons[index] = str(step_reasons[index])
        last_action = actions

    results: list[dict[str, Any]] = []
    for index, schedule in enumerate(schedules):
        arrays = finalize_accumulator(accumulators[index])
        if not reasons[index]:
            reasons[index] = "time_limit" if len(arrays["step_index"]) == duration_steps else "unexpected_termination"
        safety_flags = {
            name: int(np.count_nonzero(arrays[name]))
            for name in (
                "fall_flag",
                "base_contact",
                "actual_joint_limit_violation",
                "torque_limit_violation",
                "nan_inf_flag",
            )
        }
        accepted = (
            len(arrays["step_index"]) == duration_steps
            and reasons[index] == "time_limit"
            and not any(safety_flags.values())
            and all(np.isfinite(value).all() for name, value in arrays.items() if value.dtype.kind != "b")
        )
        metadata = {
            "schema": "expert-imitation-raw-episode-v1",
            "collector_version": SCRIPT_VERSION,
            "episode_id": schedule["episode_id"],
            "seed": schedule["seed"],
            "requested_duration_s": duration_steps * CONTROL_DT,
            "samples": int(len(arrays["step_index"])),
            "settle_seconds": settle_steps * CONTROL_DT,
            "command_schedule": schedule["segments"],
            "command_domain": DATASET_COMMAND_LIMITS.tolist(),
            "termination_reason": reasons[index],
            "accepted": bool(accepted),
            "rejection_reason": None if accepted else reasons[index],
            "safety_counts": safety_flags,
            "q_target_clipping_count": int(np.count_nonzero(arrays["q_target_clipping"])),
            "episode_disjoint_unit": True,
        }
        results.append({"schedule": schedule, "arrays": arrays, "metadata": metadata})
    return results


def save_raw_episode(root: Path, result: dict[str, Any]) -> dict[str, Any]:
    schedule = result["schedule"]
    arrays = dict(result["arrays"])
    metadata = dict(result["metadata"])
    arrays["metadata_json"] = metadata_array(metadata)
    path = root / "raw" / f"episode_{int(schedule['episode_id']):04d}.npz"
    write_deterministic_npz(path, arrays)
    metadata["raw_path"] = relative_path(path)
    metadata["raw_sha256"] = sha256_file(path)
    return metadata


def write_collection_summary(root: Path, records: list[dict[str, Any]], config: dict[str, Any]) -> None:
    accepted = [row for row in records if row["accepted"]]
    rejected = [row for row in records if not row["accepted"]]
    samples = sum(int(row["samples"]) for row in accepted)
    duration = samples * CONTROL_DT
    counts: dict[str, int] = {}
    for row in records:
        for segment in row.get("command_schedule", []):
            counts[segment["category"]] = counts.get(segment["category"], 0) + 1
    lines = [
        "# Expert rollout collection summary",
        "",
        "Collection is complete only at the raw-episode level; validation and canonical processing are performed by `validate_expert_dataset.py`.",
        "",
        f"- Collector version: `{SCRIPT_VERSION}`",
        f"- Attempted episodes: `{len(records)}`",
        f"- Accepted by runtime safety gate: `{len(accepted)}`",
        f"- Rejected: `{len(rejected)}`",
        f"- Accepted samples: `{samples}`",
        f"- Accepted duration: `{duration:.3f} s`",
        f"- Policy rate: `{POLICY_RATE_HZ} Hz`; physics rate: `{PHYSICS_RATE_HZ} Hz`; decimation: `{DECIMATION}`",
        f"- Dataset command envelope: `{DATASET_COMMAND_LIMITS.tolist()}`",
        "",
        "## Command segment categories",
        "",
        "| Category | Segment count |",
        "|---|---:|",
    ]
    lines.extend(f"| `{name}` | {count} |" for name, count in sorted(counts.items()))
    lines.extend(["", "## Rejected episodes", "", "| Episode | Samples | Reason |", "|---|---:|---|"])
    lines.extend(
        f"| `{row['episode_id']}` | {row['samples']} | `{row['rejection_reason']}` |"
        for row in rejected
    )
    lines.extend(["", "## Configuration", "", f"```json\n{canonical_json(config)}\n```"])
    write_text(root / "reports/collection_summary.md", "\n".join(lines))


def collect(args: argparse.Namespace) -> None:
    root = Path(args.output_root).resolve()
    for directory in ("frozen_contract", "scripts", "raw", "processed", "splits", "reports", "manifests", "plots"):
        (root / directory).mkdir(parents=True, exist_ok=True)
    existing_raw = sorted((root / "raw").glob("episode_*.npz"))
    if existing_raw and not args.overwrite:
        raise RuntimeError(f"refusing to mix with existing raw episodes; first raw file is {existing_raw[0]}")
    if args.episodes < 1 or args.duration_s < 10.0:
        raise ValueError("episodes must be positive and duration_s must allow bounded command segments")
    duration_steps = int(round(args.duration_s / CONTROL_DT))
    if not math.isclose(duration_steps * CONTROL_DT, args.duration_s, abs_tol=1.0e-9):
        raise ValueError("duration_s must be an exact multiple of 0.02 s")
    if args.batch_size < 1:
        raise ValueError("batch_size must be positive")

    # Cache setup is intentionally performed before Genesis initializes.
    from scripts.imitation_learning.run_expert_compatibility_gate import configure_caches

    cache_paths = configure_caches()
    from scripts.imitation_learning.run_expert_validation import make_teacher_observation
    from scripts.imitation_learning.collect_command_teacher_rollouts import FrozenTeacher
    from learned_execution.genesis_deployment_scene import GenesisDeploymentScene

    artifacts = artifact_manifest()
    write_json(root / "manifests/expert_artifact_manifest.json", artifacts)
    teacher = FrozenTeacher(CHECKPOINT, torch_threads=args.torch_threads)
    if teacher.observation_dim != 45 or teacher.action_dim != ACTION_DIM:
        raise RuntimeError("frozen expert tensor dimensions do not match 45->12")

    base_seed = int(args.base_seed)
    schedules: list[dict[str, Any]] = []
    for episode_id in range(args.episodes):
        seed = base_seed + episode_id
        commands, segment_ids, transition_window, segments = make_schedule(episode_id, seed, duration_steps)
        schedules.append(
            {
                "episode_id": episode_id,
                "seed": seed,
                "commands": commands,
                "segment_ids": segment_ids,
                "transition_window": transition_window,
                "segments": segments,
            }
        )

    collection_config = {
        "schema": "expert-imitation-collection-config-v1",
        "collector_version": SCRIPT_VERSION,
        "episodes": args.episodes,
        "requested_duration_s": args.duration_s,
        "duration_steps": duration_steps,
        "batch_size": args.batch_size,
        "base_seed": base_seed,
        "settle_seconds": args.settle_s,
        "settle_steps": int(round(args.settle_s / CONTROL_DT)),
        "command_domain": DATASET_COMMAND_LIMITS.tolist(),
        "randomization": "none beyond deterministic episode schedule; flat plane, frozen Genesis physics, fixed PD, fixed robot and expert",
        "cache_paths": cache_paths,
        "artifact_manifest_sha256": sha256_file(root / "manifests/expert_artifact_manifest.json"),
        "collection_script_sha256": sha256_file(Path(__file__)),
    }
    write_json(root / "manifests/collection_config.json", collection_config)

    records: list[dict[str, Any]] = []
    scene = GenesisDeploymentScene(args.batch_size)
    try:
        settle_steps = int(round(args.settle_s / CONTROL_DT))
        for start in range(0, args.episodes, args.batch_size):
            batch = schedules[start : start + args.batch_size]
            # The scene is fixed-size; pad the last batch with deterministic
            # duplicate schedules and discard those padding records.
            padded = list(batch)
            while len(padded) < args.batch_size:
                padded.append(batch[-1])
            results = run_batch(scene, teacher, padded, settle_steps, make_teacher_observation)
            for result, schedule in zip(results[: len(batch)], batch, strict=True):
                record = save_raw_episode(root, result)
                record["episode_id"] = f"episode_{int(schedule['episode_id']):04d}"
                record["seed"] = int(schedule["seed"])
                record["duration_s"] = float(args.duration_s)
                record["expert_checkpoint_sha256"] = artifacts["artifacts"]["checkpoint"]["sha256"]
                record["genesis_version"] = artifacts["genesis"]["version"]
                record["robot_config"] = artifacts["robot_asset"]
                record["pd_config"] = artifacts["control"]
                record["collection_script_sha256"] = collection_config["collection_script_sha256"]
                records.append(record)
            print(
                f"completed episodes {start + 1}-{start + len(batch)}/{args.episodes}; "
                f"accepted={sum(bool(row['accepted']) for row in records)}",
                flush=True,
            )
    finally:
        close = getattr(scene, "close", None)
        if callable(close):
            close()

    manifest = {
        "schema": "episode-manifest-v1",
        "generated_utc": utc_now(),
        "collector_version": SCRIPT_VERSION,
        "attempted_episodes": len(records),
        "accepted_episodes": sum(bool(row["accepted"]) for row in records),
        "rejected_episodes": sum(not bool(row["accepted"]) for row in records),
        "expert_artifact_manifest": relative_path(root / "manifests/expert_artifact_manifest.json"),
        "collection_config": relative_path(root / "manifests/collection_config.json"),
        "episodes": records,
    }
    write_json(root / "manifests/episode_manifest.json", manifest)
    write_collection_summary(root, records, collection_config)
    print(json.dumps({
        "attempted_episodes": len(records),
        "accepted_episodes": manifest["accepted_episodes"],
        "rejected_episodes": manifest["rejected_episodes"],
        "accepted_samples": sum(int(row["samples"]) for row in records if row["accepted"]),
        "output_root": str(root),
    }, indent=2))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, default=DATASET_ROOT)
    parser.add_argument("--episodes", type=int, default=120)
    parser.add_argument("--duration-s", type=float, default=40.0)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--base-seed", type=int, default=2026081600)
    parser.add_argument("--settle-s", type=float, default=SETTLE_SECONDS)
    parser.add_argument("--torch-threads", type=int, default=1)
    parser.add_argument("--overwrite", action="store_true", help="allow replacing raw episode files in the selected output root")
    return parser.parse_args()


if __name__ == "__main__":
    collect(parse_args())
